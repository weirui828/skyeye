#!/usr/bin/env python3
"""Regenerate Sources/SkyEyeCore/CloudRanges.swift from the prefixes each network announces.

Run it by hand when the ranges look stale: python3 scripts/cloud-ranges.py
It asks RIPEstat (stat.ripe.net) for the announced prefixes of the AS numbers below. Only the AS numbers are sent.
"""
import datetime
import ipaddress
import json
import pathlib
import urllib.request

NETWORKS = [
    ("Tencent Cloud", [132203]),          # Tencent Cloud outside mainland China
    ("Tencent", [45090]),                 # Shenzhen Tencent: Tencent Cloud in China and Tencent's own services
    ("Alibaba Cloud", [45102, 37963]),    # Alibaba Cloud international, and Aliyun in China
]
OUT = pathlib.Path(__file__).resolve().parent.parent / "Sources/SkyEyeCore/CloudRanges.swift"


def announced(asn):
    url = f"https://stat.ripe.net/data/announced-prefixes/data.json?resource=AS{asn}"
    with urllib.request.urlopen(url, timeout=60) as response:
        prefixes = json.load(response)["data"]["prefixes"]
    return [ipaddress.ip_network(p["prefix"]) for p in prefixes]


def main():
    lines = []
    for owner, asns in NETWORKS:
        networks = [n for asn in asns for n in announced(asn)]
        for version in (4, 6):
            merged = ipaddress.collapse_addresses(n for n in networks if n.version == version)
            lines += [f'        ("{n}", "{owner}"),' for n in sorted(merged)]
    today = datetime.date.today().isoformat()
    sources = "; ".join(f"{owner}: " + ", ".join(f"AS{a}" for a in asns) for owner, asns in NETWORKS)
    OUT.write_text(
        "// Generated by scripts/cloud-ranges.py on " + today + ". Do not edit by hand.\n"
        "// Prefixes announced by " + sources + " (RIPEstat).\n\n"
        "enum CloudRanges {\n"
        "    static let all: [(range: String, owner: String)] = [\n"
        + "\n".join(lines)
        + "\n    ]\n}\n"
    )
    print(f"Wrote {len(lines)} ranges to {OUT}")


if __name__ == "__main__":
    main()
